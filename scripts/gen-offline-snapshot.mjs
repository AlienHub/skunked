import fs from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { validateApps, readJsonFile, getDatasetRoot } from "./open-data-lib.mjs"

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const OUTPUT_PATH = path.resolve(
  __dirname,
  "..",
  "src",
  "data",
  "officialRegistry.ts"
)

function formatStringArray(values, indent) {
  if (values.length === 0) return "[]"

  const items = values.map((value) => `${indent}  ${JSON.stringify(value)}`)
  return `[\n${items.join(",\n")}\n${indent}]`
}

function formatApp(app) {
  return `  {
    id: ${JSON.stringify(app.id)},
    slug: ${JSON.stringify(app.slug)},
    name: ${JSON.stringify(app.name)},
    nameEn: ${JSON.stringify(app.nameEn)},
    category: ${JSON.stringify(app.category)},
    officialDomains: ${formatStringArray(app.officialDomains, "    ")},
    officialUrls: ${formatStringArray(app.officialUrls, "    ")},
    keywords: ${formatStringArray(app.keywords, "    ")}
  }`
}

function buildRegistrySource(apps, generatedAt) {
  const appBlocks = apps.map(formatApp).join(",\n")

  return `import { OfficialSoftware } from "../types"

/**
 * AUTO-GENERATED by scripts/gen-offline-snapshot.mjs — DO NOT EDIT
 * Source of truth: open-data/apps.json
 * Generated at: ${generatedAt}
 */
export const OFFICIAL_SOFTWARE_REGISTRY: OfficialSoftware[] = [
${appBlocks}
]

export function getSoftwareByName(name: string): OfficialSoftware | undefined {
  return OFFICIAL_SOFTWARE_REGISTRY.find(
    (s) => s.name === name || s.nameEn.toLowerCase() === name.toLowerCase()
  )
}

export function getSoftwareByDomain(
  domain: string
): OfficialSoftware | undefined {
  const normalizedDomain = domain.toLowerCase()
  return OFFICIAL_SOFTWARE_REGISTRY.find((software) =>
    software.officialDomains.some(
      (officialDomain) =>
        normalizedDomain.includes(officialDomain.toLowerCase()) ||
        officialDomain.toLowerCase().includes(normalizedDomain)
    )
  )
}

export function getAllOfficialDomains(): string[] {
  return OFFICIAL_SOFTWARE_REGISTRY.flatMap((s) => s.officialDomains)
}

export function getAllKeywords(): string[] {
  return OFFICIAL_SOFTWARE_REGISTRY.flatMap((s) => s.keywords)
}
`
}

async function main() {
  const appsPath = path.join(getDatasetRoot(), "apps.json")
  const appsRaw = await readJsonFile(appsPath)
  const apps = validateApps(appsRaw)
  const generatedAt = new Date().toISOString()
  const source = buildRegistrySource(apps, generatedAt)

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true })
  await fs.writeFile(OUTPUT_PATH, source, "utf8")

  console.log(`Generated offline snapshot: ${OUTPUT_PATH}`)
  console.log(`- apps: ${apps.length}`)
  console.log(`- official domains: ${apps.reduce((acc, app) => acc + app.officialDomains.length, 0)}`)
}

main().catch((error) => {
  console.error(`Failed to generate offline snapshot: ${error.message}`)
  process.exitCode = 1
})
